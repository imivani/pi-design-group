import {chromium} from '@playwright/test';
import {mkdir,rename,writeFile} from 'node:fs/promises';
const dir='design/review';
await mkdir(`${dir}/home-return-recording`,{recursive:true});
const browser=await chromium.launch({channel:'chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference',recordVideo:{dir:`${dir}/home-return-recording`,size:{width:1440,height:1000}}});
await context.addInitScript(()=>{
  localStorage.setItem('pi-motion','system');
  window.__returnReport=[];
  document.addEventListener('pi:home-return',event=>window.__returnReport.push({phase:event.detail.phase,duration:getComputedStyle(document.documentElement,'::view-transition-new(root)').animationDuration,copyName:document.querySelector('.hero-copy')?.style.viewTransitionName}));
});
const page=await context.newPage();
await page.goto('http://127.0.0.1:4321/darcy');
await page.waitForTimeout(1100);
await page.screenshot({path:`${dir}/home-return-before.png`});
await page.locator('#site-header .site-wordmark').hover();
await page.waitForTimeout(450);
await page.locator('#site-header .site-wordmark').click();
await page.waitForURL('**/#hero');
await page.waitForTimeout(100);
await page.screenshot({path:`${dir}/home-return-moving.png`});
await page.waitForTimeout(900);
await page.screenshot({path:`${dir}/home-return-complete.png`});
const report=await page.evaluate(()=>({events:window.__returnReport,state:document.documentElement.dataset.homeReturn,remainingNames:document.querySelectorAll('[data-pi-transition]').length,videoPlaying:!document.querySelector('#hero-video').paused,overflow:document.documentElement.scrollWidth>innerWidth,scrollY}));
await page.waitForTimeout(600);
const video=page.video();
await context.close();
await rename(await video.path(),`${dir}/home-return-motion.webm`);
await writeFile(`${dir}/home-return-report.json`,JSON.stringify(report,null,2));
await browser.close();
console.log(JSON.stringify(report,null,2));
