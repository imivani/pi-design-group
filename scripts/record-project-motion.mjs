import {chromium} from '@playwright/test';
const browser=await chromium.launch({channel:'chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:'design/review/recordings',size:{width:1440,height:1000}}});
await context.addInitScript(()=>localStorage.setItem('pi-motion','system'));
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:4321/crestmontwest');await page.waitForTimeout(600);
await page.locator('#project-hero-next').click();await page.waitForTimeout(600);
