await page.locator('.drawing-story').scrollIntoViewIfNeeded();await page.waitForTimeout(700);
await page.locator('.drawing-plan .gallery-link').click();await page.waitForTimeout(700);
await page.keyboard.press('Escape');await page.waitForTimeout(550);
const reveals=await page.locator('[data-reveal]').evaluateAll(elements=>elements.map(element=>({group:element.className,state:element.dataset.revealState,opacity:getComputedStyle(element).opacity})));
await context.close();await page.video().saveAs('design/review/project-motion.webm');await browser.close();
